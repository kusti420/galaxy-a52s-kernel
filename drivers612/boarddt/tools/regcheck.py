#!/usr/bin/env python3
"""regcheck.py <regulators-r02.txt> <phone-merged.dtb> <our-merged.dtb> <out.md>
Every RPMh regulator of the phone: min/max/init of the table, plus every property of the
regulator node and of its RPMh resource node (modes, thresholds, set, always-on, boot-on),
phone 5.4 tree vs our merged 6.12 tree. Matched by label."""
import os, re, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fdt
ph, our = fdt.load(sys.argv[2]), fdt.load(sys.argv[3])
ps, os_ = fdt.symbols(ph), fdt.symbols(our)
def u(n, p):
    v = n.props.get(p)
    return struct.unpack(">I", v)[0] if v and len(v) == 4 else None
def parent(root, path):
    return root.get(path.rsplit("/", 1)[0])
rows, nbad, n = [], 0, 0
for line in open(sys.argv[1]):
    m = re.match(r"(\w+)\s+(\S+)\s+(\S+)\s+min=\s*(\S+)\s+max=\s*(\S+)\s+init=\s*(\S+)", line)
    if not m:
        continue
    kind, res, labels, mn, mx, init = m.groups()
    label = labels.split(",")[0]
    n += 1
    if label not in ps or label not in os_:
        rows.append("| %s | %s | %s | - | **label missing (%s)** |" % (kind, res, label, "phone" if label not in ps else "ours")); nbad += 1; continue
    a, b = ph.get(ps[label]), our.get(os_[label])
    problems = []
    for prop, want in (("regulator-min-microvolt", mn), ("regulator-max-microvolt", mx), ("qcom,init-voltage", init)):
        got = u(b, prop)
        if want != "-" and got != int(want):
            problems.append("%s table %s ours %s" % (prop, want, got))
    for x, y, where in ((a, b, ""), (parent(ph, ps[label]), parent(our, os_[label]), "resource: ")):
        for p in sorted(set(x.props) | set(y.props)):
            if p in ("phandle", "linux,phandle") or p.endswith("-supply") or p == "proxy-supply":
                continue
            if x.props.get(p) != y.props.get(p):
                f = lambda v: "absent" if v is None else (v.hex() if v else "present")
                problems.append("%s%s phone %s ours %s" % (where, p, f(x.props.get(p)), f(y.props.get(p))))
    flags = " ".join(k for k in ("regulator-always-on", "regulator-boot-on") if k in b.props)
    rows.append("| %s | %s | %s | %s / %s / %s %s | %s |" % (kind, res, label, u(b, "regulator-min-microvolt"), u(b, "regulator-max-microvolt"),
                u(b, "qcom,init-voltage"), flags, "identical" if not problems else "**" + "; ".join(problems) + "**"))
    nbad += bool(problems)
with open(sys.argv[4], "w") as f:
    f.write("# RPMh regulators: phone 5.4 tree vs our merged 6.12 tree (generated by tools/regcheck.py)\n\n"
            "%d regulators of downstream-dt/regulators-r02.txt, %d not identical. Compared: min/max/init against the table and every\n"
            "property of the regulator node and its resource node (supply phandles excluded).\n\n"
            "| kind | resource | label | ours: min / max / init (uV or level), flags | result |\n|---|---|---|---|---|\n%s\n" % (n, nbad, "\n".join(rows)))
print("regulators: %d checked, %d not identical to the phone (REGULATORS.md)" % (n, nbad))
sys.exit(1 if nbad else 0)
