#!/usr/bin/env python3
"""bindings.py <nodes-compat.tsv> <compat-index.txt> <out.md>: which node has a 6.12 driver."""
import sys, collections
idx = collections.defaultdict(set)
for line in open(sys.argv[2]):
    c, _, f = line.rstrip("\n").partition("\t")
    idx[c].add(f)
GENERIC = {"simple-bus", "regulator-fixed", "gpio-keys", "gpio-leds", "simple-mfd", "syscon", "shared-dma-pool", "ramoops", "removed-dma-pool"}
def where(fs):
    def tag(f):
        if f.startswith("drivers612/") or f.startswith("samsung612/") or f.startswith("modules/") or f.startswith("bsp612/techpacks/"):
            return "/".join(f.split("/")[:3] if f.startswith("bsp612") else f.split("/")[:2])
        for k, v in (("bsp612/kernel/", "GKI/ACK"), ("bsp612/soc-repo", "soc-repo"), ("bsp612/techpacks/", "techpack:"),
                     ("samsung612/", "samsung612:"), ("drivers612/", "drivers612:"), ("modules/", "modules:")):
            if f.startswith(k):
                parts = f.split("/")
                return v + (parts[2] if v.endswith(":") and len(parts) > 2 else "") if v.endswith(":") and k != "drivers612/" and k != "modules/" else (v + parts[1] if v.endswith(":") else v)
        return f
    return sorted({tag(f) for f in fs})
rows = collections.defaultdict(list); stat = collections.Counter()
for line in open(sys.argv[1]):
    sub, node, comp, status = line.rstrip("\n").split("\t")
    cs2 = comp.split("|")
    real = [(c, where({f for f in idx[c] if "/donors/" not in f and "/orig/" not in f})) for c in cs2 if c in idx]
    real = [(c, w) for c, w in real if w]
    donor = [(c, sorted({"/".join(f.split("/")[:3]) for f in idx[c] if "/donors/" in f})) for c in cs2 if c in idx]
    donor = [(c, w) for c, w in donor if w]
    hits = real
    if not hits and donor:
        verdict = "no 6.12 driver in the project yet; donor source: " + "; ".join("`%s` (%s)" % (c, ", ".join(w)) for c, w in donor); stat[sub, "none"] += 1
    elif hits:
        verdict = "driver in 6.12: " + "; ".join("`%s` (%s)" % (c, ", ".join(w)) for c, w in hits); stat[sub, "have"] += 1
    elif any(c in GENERIC for c in cs2):
        verdict = "generic binding (core kernel)"; stat[sub, "have"] += 1
    else:
        verdict = "**no 6.12 driver found**"; stat[sub, "none"] += 1
    rows[sub].append("| `%s` | %s | %s | %s |" % (node, " ".join("`%s`" % c for c in cs2), status or "-", verdict))
with open(sys.argv[3], "w") as f:
    f.write("# Binding table (generated by tools/bindings.py)\n\nPer node of the phone's board tree that has a `compatible`: is there a driver matching that\nstring in the 6.12 trees (GKI, soc-repo, bsp612/techpacks, samsung612, drivers612, modules)?\n"
            "\"driver in 6.12\" means the of_match string exists; property parsing was NOT compared\nautomatically (see README, section Binding review, for the nodes checked by hand).\n\n| Subsystem | nodes with a 6.12 driver | nodes without |\n|---|---|---|\n")
    for sub in rows:
        f.write("| %s | %d | %d |\n" % (sub, stat[sub, "have"], stat[sub, "none"]))
    for sub, rs in rows.items():
        f.write("\n## %s\n\n| Node (target/path) | compatible | status | 6.12 driver |\n|---|---|---|---|\n%s\n" % (sub, "\n".join(rs)))
print("bindings:", sum(v for (s, k), v in stat.items() if k == "have"), "with driver,", sum(v for (s, k), v in stat.items() if k == "none"), "without")
