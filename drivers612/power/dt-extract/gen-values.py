#!/usr/bin/env python3
"""Generate ../DT-VALUES.md: the safety-critical values of a52sxq-power.dtsi in decimal, each
with its line in downstream-dt/a52sxq-r02.dts. Decoding is mechanical (hex -> signed dec)."""
import re,os
H=os.path.dirname(os.path.abspath(__file__))
src=open(H+'/../../../downstream-dt/a52sxq-r02.dts').read().split('\n')
def find(prop,lo=1,hi=10**9):
    for i,l in enumerate(src,1):
        if lo<=i<=hi and re.match(r'\s*'+re.escape(prop)+r'( = |;)',l): return i,l.strip()
    return None,None
def dec(v):
    out=[]
    for x in v.split():
        n=int(x,16) if x.startswith('0x') else int(x)
        if n>=0x80000000: n-=1<<32
        out.append(str(n))
    return ' '.join(out)
def row(prop,unit,note='',lo=1,hi=10**9,maxn=40):
    i,l=find(prop,lo,hi)
    if i is None: return '| `%s` | NOT IN DT | | %s |'%(prop,note)
    m=re.search(r'<(.*)>',l)
    if m:
        d=dec(m.group(1)); n=len(d.split())
        val=d if n<=maxn else '%d cells: %s ... %s'%(n,' '.join(d.split()[:6]),' '.join(d.split()[-3:]))
    elif '"' in l: val=l.split('=',1)[1].strip(' ;')
    else: val='(present, boolean)'
    return '| `%s` | %s | %s | %s%s |'%(prop,val,i,unit,(' — '+note) if note else '')
