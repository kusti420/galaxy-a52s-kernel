#!/bin/bash
# drivers612/modem/build.sh: everything for the modem/IPA/rmnet test on the 6.12 BSP, built and
# assembled OFFLINE. Nothing here touches a phone; nothing is flashed.
#
#   ./build.sh            build a52_modem_guard.ko + dev_ril_bridge.ko, assemble
#                         out/stage-modem (sync stage) and out/stage-radio (radio@adsp stage),
#                         the kernel-only test pack out/pack-modem.tgz, and the modem DT
#                         (out/android-modem-r02.dtb via dt/mkmodemtree.sh)
#   ./build.sh clean
#
# Reads (never writes) bsp612/ (kernel, out/lahaina, out/dist, soc-repo-staging Module.symvers,
# out/bringup/load.list), drivers612/conn/ (data modules, drb source, qrtrls),
# drivers612/androidboot/out/stage-*/load.list (what earlier stages already load).
# HARD RULE (2026-11-13 incident): no firmware image (.mdt/.bNN/.mbn) is ever packed here; the
# modem only ever gets the phone's OWN image from its own partition. The checks below enforce it.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd); TOP=$(cd "$HERE/../.." && pwd); BSP=$TOP/bsp612
CLANG=${ANDROID_TREE:-$HOME/android}/prebuilts/clang/host/linux-x86/clang-r547379/bin
KREL=$(cat "$BSP/out/lahaina/include/config/kernel.release")
DIST=$BSP/out/dist/lib/modules/$KREL
DATA=$TOP/drivers612/conn/data/out/lib/modules/$KREL/extra
AB=$TOP/drivers612/androidboot/out
OUT=$HERE/out
fail() { echo "FAILED: $*" >&2; exit 1; }
[ "${1:-}" = clean ] && { rm -rf "$OUT"; exit 0; }

# ---- 1. our two modules, out of tree against bsp612/out/lahaina (read only)
mkdir -p "$OUT/build"
rm -rf "$OUT/build/guard" "$OUT/build/drb"
cp -r "$HERE/guard" "$OUT/build/guard"
mkdir -p "$OUT/build/drb"; cp -r "$TOP/drivers612/conn/rild/drb/"{Kbuild,dev_ril_bridge.c,include} "$OUT/build/drb/"
export KBUILD_BUILD_USER=android-build KBUILD_BUILD_HOST=localhost
for m in guard drb; do
	make -C "$BSP/kernel" O="$BSP/out/lahaina" ARCH=arm64 LLVM="$CLANG/" M="$OUT/build/$m" \
		KBUILD_EXTRA_SYMBOLS="$BSP/soc-repo-staging/build/Module.symvers" -j8 modules \
		> "$OUT/build/$m.log" 2>&1 || { tail -20 "$OUT/build/$m.log"; fail "build $m"; }
	grep -E "warning:|error:" "$OUT/build/$m.log" && fail "$m: compiler warnings (see $OUT/build/$m.log)"
done
echo "built: a52_modem_guard.ko dev_ril_bridge.ko ($KREL)"

# ---- 2. module tree for dependency resolution: GKI + soc-repo + conn/data + ours
T=$OUT/depmod; rm -rf "$T"; mkdir -p "$T/lib/modules/$KREL/extra"
cp -a "$DIST/." "$T/lib/modules/$KREL/"
cp "$DATA"/*.ko "$OUT/build/guard/a52_modem_guard.ko" "$OUT/build/drb/dev_ril_bridge.ko" "$T/lib/modules/$KREL/extra/"
depmod -e -F "$BSP/out/gki/System.map" -b "$T" "$KREL" > "$OUT/depmod.log" 2>&1 || true
[ -s "$OUT/depmod.log" ] && { cat "$OUT/depmod.log"; fail "depmod reports unresolved symbols"; }
# modules an earlier stage loads already (first stage + the sync stages before "modem")
EARLY="secure display kgsl i2c nfc touch fingerprint power vibrator camera dsp debug"
{ sed 's/[[:space:]].*//' "$BSP/out/bringup/load.list"
  for s in $EARLY; do [ -f "$AB/stage-$s/load.list" ] && grep -vE '^[[:space:]]*(#|$)' "$AB/stage-$s/load.list" | sed 's/[[:space:]].*//'; done
} | sed 's#.*/##; s#^[0-9][0-9]*-##' | sort -u > "$OUT/already-loaded.txt"
# the kernel-only test (bsp612 ramdisk, no Android stages) has only the first stage + dsp
{ sed 's/[[:space:]].*//' "$BSP/out/bringup/load.list"; grep -vE '^[[:space:]]*(#|$)' "$AB/stage-dsp/load.list" | sed 's/[[:space:]].*//'
} | sed 's#.*/##; s#^[0-9][0-9]*-##' | sort -u > "$OUT/already-loaded-kernelonly.txt"
ALREADY=$OUT/already-loaded.txt
LATE=$(for s in wlanb wlan audio powerpd; do [ -f "$AB/stage-$s/load.list" ] && grep -vE '^[[:space:]]*(#|$)' "$AB/stage-$s/load.list" | sed 's/[[:space:]].*//'; done | sort -u)

stage() { # stage <name> <targets file>: resolve deps, copy .ko, write load.list
	local n=$1 tf=$2 d=$OUT/stage-$1 m args f line
	rm -rf "$d"; mkdir -p "$d"; : > "$d/load.list"
	echo "# generated by drivers612/modem/build.sh from $(basename "$(dirname "$tf")")/$(basename "$tf"); $(date -I)" >> "$d/load.list"
	grep -vE '^[[:space:]]*(#|$)' "$tf" | while read -r m args; do
		# hard dependencies only, from modules.dep (depmod lists the whole closure; kmod loads
		# it in reverse order, then the module). Not "modprobe --show-depends": that adds
		# softdeps, e.g. dwc3_msm's "pre: phy-msm-ssusb-qmp" (the SS PHY: must not be probed
		# behind the USB link's back; dwc3-msm itself is in the first stage already).
		awk -v want="${m%.ko}" -v base="$T/lib/modules/$KREL/" '
			{ p = $1; sub(":$", "", p); n = p; sub(".*/", "", n); sub("\\.ko$", "", n); gsub("-", "_", n)
			  w = want; gsub("-", "_", w)
			  if (n == w) { for (i = NF; i >= 2; i--) print base $i; print base p; exit } }' \
			"$T/lib/modules/$KREL/modules.dep" |
		while read -r f; do
			b=$(basename "$f")
			grep -qx "$b" "$ALREADY" && continue
			grep -q "^$b\( \|$\)" "$d/load.list" && continue
			echo "$LATE" | grep -x "$b" >/dev/null && echo "note: $b is also in a later stage (it will report EEXIST there)"
			cp "$f" "$d/"
			if [ "$b" = "$m" ] && [ -n "$args" ]; then echo "$b $args" >> "$d/load.list"; else echo "$b" >> "$d/load.list"; fi
		done
		grep -q "^$m\( \|$\)" "$d/load.list" || grep -qx "$m" "$ALREADY" || fail "$m: not resolved (modules.dep)"
	done
	[ -f "$(dirname "$tf")/pre.sh" ] && cp "$(dirname "$tf")/pre.sh" "$d/pre.sh"
	for f in "$d"/*.ko; do
		"$CLANG/llvm-strip" --strip-debug "$f"
		strings "$f" | grep "^vermagic=$KREL " >/dev/null || fail "wrong vermagic: $f"
	done
	ls "$d" | grep -E '\.(mdt|mbn|b[0-9][0-9])$' && fail "firmware image in $d"
	echo "stage $n: $(grep -vc '^#' "$d/load.list") modules -> $d/load.list"
}
stage modem "$HERE/stages/modem/targets.txt"
stage radio "$HERE/stages/radio/load.list"
sed -i "1a # load as a52.mods=...,dsp,modem,...,radio@adsp,... (see README)" "$OUT/stage-radio/load.list"

# ---- 3. kernel-only test pack (busybox shell of the bsp612 ramdisk, no Android): modules of
# the dsp + modem stages + the test scripts. Unpacked to /p by kexec/kx-cycle (KX_PACK).
K=$OUT/kpack; rm -rf "$K"; mkdir -p "$K/m"
cp "$HERE/kpack/"*.sh "$K/"
cp "$TOP/drivers612/conn/tools/qrtrls" "$K/"
cp "$TOP/drivers612/hwbringup/mkdevs" "$K/" 2>/dev/null || cp "$TOP/drivers612/wifibt/pack/mkdevs" "$K/"
# HARD RULE (owner, 2026-11-14): the microSD card is never touched: the packed mkdevs makes no
# mmcblk* nodes (the copy is filtered here; the shared hwbringup/mkdevs stays as it is)
sed -i 's@^\t\[ -e "/dev/\$DEVNAME" \] && continue$@&\n\tcase "$DEVNAME" in mmcblk*|block/mmcblk*) continue;; esac  # microSD: never (HARD RULE)@' "$K/mkdevs"
grep -q 'mmcblk\*|block/mmcblk\*) continue' "$K/mkdevs" || fail "mkdevs: mmcblk filter not applied"
grep -vE '^[[:space:]]*(#|$)' "$AB/stage-dsp/load.list" > "$K/dsp.list"
cp $(sed "s#^#$AB/stage-dsp/#" "$K/dsp.list") "$K/m/"
ALREADY=$OUT/already-loaded-kernelonly.txt stage kmodem "$HERE/stages/modem/targets.txt" >/dev/null
grep -vE '^[[:space:]]*(#|$)' "$OUT/stage-kmodem/load.list" > "$K/modem.list"
cp "$OUT/stage-kmodem/"*.ko "$K/m/"
# Test T1 (m1.sh argument "therm"): PMIC VADC + deps, loaded only when asked for
ALREADY=$OUT/already-loaded-kernelonly.txt stage ktherm "$HERE/stages/therm/targets.txt" >/dev/null
grep -vE '^[[:space:]]*(#|$)' "$OUT/stage-ktherm/load.list" > "$K/therm.list"
cp "$OUT/stage-ktherm/"*.ko "$K/m/"
# M2-K (m1.sh argument "m2"): static aarch64 rmtfs (RAM-only build), tqftpserv, qrtr-lookup, efsdump
OUT="$OUT/userspace" "$HERE/userspace/build.sh" > "$OUT/userspace.log" 2>&1 || { tail -20 "$OUT/userspace.log"; fail "userspace build"; }
mkdir -p "$K/bin"; cp "$OUT/userspace/bin/"{rmtfs,tqftpserv,qrtr-lookup,efsdump,qmi-nas} "$K/bin/"
echo "userspace for m2: $(cd "$K/bin" && echo *)"
ls "$K" "$K/m" "$K/bin" | grep -E '\.(mdt|mbn|b[0-9][0-9])$' && fail "firmware image in the test pack"
# microSD HARD RULE: no script or binary in the pack names mmcblk, except the refusals in
# efsdump and the packed mkdevs filter (both checked above / in userspace/build.sh)
for f in "$K"/*.sh "$K/bin/"*; do
	case "$f" in */bin/efsdump) continue;; esac
	grep -qa mmcblk "$f" && fail "$(basename "$f") mentions mmcblk (microSD must never be touched)"
done
grep -n mmcblk "$K/mkdevs" | grep -v 'continue;; esac  # microSD: never' && fail "mkdevs mentions mmcblk outside the filter"
(cd "$K" && tar czf "$OUT/pack-modem.tgz" --owner=0 --group=0 .)
echo "kernel-only test pack: $OUT/pack-modem.tgz ($(stat -c %s "$OUT/pack-modem.tgz") bytes)"

# ---- 4. the modem device tree (input: the current Android test tree, read only)
"$HERE/dt/mkmodemtree.sh" "${BASE_DTB:-$TOP/out-ack/kx/android-r02.dtb}" "$OUT/android-modem-r02.dtb"

# ---- 5. resolved load lists, kept in git for review (out/ is ignored)
grep -v '^# generated' "$OUT/stage-modem/load.list" > "$HERE/stages/modem/resolved.list"
grep -v '^# generated' "$OUT/stage-kmodem/load.list" > "$HERE/stages/modem/resolved-kernelonly.list"
echo "resolved lists: stages/modem/resolved.list, stages/modem/resolved-kernelonly.list"
