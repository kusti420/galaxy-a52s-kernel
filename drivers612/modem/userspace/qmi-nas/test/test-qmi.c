/*
 * Host unit test of the qmi-nas codec (qmi.c). Run by userspace/build.sh:
 *   cc -I.. test-qmi.c ../qmi.c && ./a.out
 * Vectors: three NAS responses from libqmi's src/libqmi-glib/test/test-generated.c (the bytes
 * after the 6-byte QMUX header, which QRTR does not carry; test data only, not built into
 * qmi-nas) and hand-made messages for DMS, UIM, WDS and the error paths.
 */
#define _GNU_SOURCE
#include "qmi.h"

#include <stdlib.h>
#include <string.h>

static int fails, checks;

static uint8_t fixbuf[512];
/* copy a hand-made response and set its header length field from the array size */
static const uint8_t *fixlen(const uint8_t *b, size_t n)
{
	memcpy(fixbuf, b, n);
	fixbuf[5] = (uint8_t)((n - 7) & 0xff);
	fixbuf[6] = (uint8_t)((n - 7) >> 8);
	return fixbuf;
}

static char *show(int svc, const uint8_t *b, size_t n, int *rc)
{
	char *s = NULL;
	size_t l = 0;
	FILE *o = open_memstream(&s, &l);

	*rc = qmi_print(o, svc, b, n, 0);
	fclose(o);
	return s;
}

static void expect(const char *what, const char *text, const char *sub)
{
	checks++;
	if (!strstr(text, sub)) {
		fails++;
		printf("FAIL %s: missing \"%s\" in:\n%s\n", what, sub, text);
	}
}

static void expect_not(const char *what, const char *text, const char *sub)
{
	checks++;
	if (strstr(text, sub)) {
		fails++;
		printf("FAIL %s: unexpected \"%s\" in:\n%s\n", what, sub, text);
	}
}

static void expect_int(const char *what, long got, long want)
{
	checks++;
	if (got != want) {
		fails++;
		printf("FAIL %s: got %ld, want %ld\n", what, got, want);
	}
}

