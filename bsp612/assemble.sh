#!/bin/bash
# Assembles the Qualcomm KERNEL.PLATFORM.5.0 (6.12) source layout for target lahaina / yupik
# under bsp612/, for a plain-make build (no bazel/kleaf). Idempotent: run it again after
# changing a patch; it rebuilds soc-repo/, soc-repo-staging/ and devicetree/ from the donors.
# It only copies and patches files. It runs no script from the donor trees.
#
# How KERNEL.PLATFORM.5.0 is put together (from soc-repo's BUILD.bazel, kleaf-scripts/ and
# build/Makefile + build/common_sources.mk, which is Qualcomm's own non-bazel path):
#   kernel_platform/common    = ACK android16-6.12, UNMODIFIED, built with gki_defconfig.
#                               This gives the GKI Image and the GKI modules.
#   kernel_platform/soc-repo  = clo/la/kernel/qcom (kernel.lnx.6.12.*). NOT a kernel tree and
#                               not merged into common: an overlay of Qualcomm drivers that is
#                               built as ONE external module tree (DDK) against the GKI kernel.
#                               Its Kconfig files are hooked into the ACK Kconfig through the
#                               ANDROID hook  source "$(KCONFIG_EXT_PREFIX)Kconfig.ext"
#                               (Kconfig.ext = Kconfig.msm), and the target's config dict
#                               (configs/lahaina_perf.bzl) is a defconfig fragment applied on
#                               top of gki_defconfig for the module build and the dtb build
#                               only. The Image stays pure GKI.
#   soc-repo-staging          = ACK's drivers/ and net/ .c/.h files with soc-repo laid over
#                               them, so soc-repo Makefiles can also build unmodified ACK
#                               drivers that GKI leaves out (clk-qcom, ufs-qcom, dwc3-qcom...).
#                               Three files are ACK sources + a soc-repo .diff.
#   devicetree                = clo/la/platform/vendor/qcom-opensource/devicetree, used as
#                               dtstree (arch/arm64/boot/dts/vendor), headers from soc-repo
#                               (DTC_INCLUDE=soc-repo/include), DTC_FLAGS=-@.
#   soc-repo/android/ACK_SHA  names the ACK commit this soc-repo snapshot was made against.
set -euo pipefail
BSP=$(cd "$(dirname "$0")" && pwd)
DONORS=$BSP/../donors
ACK_TAG=android16-6.12-2026-06_r3
ACK_SHA=8a69376da734aa00bb02cd1155489c74454e4487   # = donors/clo-kernel-6.12/android/ACK_SHA

# 1. ACK (the kernel proper). Shallow, at the tag that peels to ACK_SHA.
if [ ! -d "$BSP/kernel/.git" ]; then
  git clone --depth 1 --branch "$ACK_TAG" https://android.googlesource.com/kernel/common "$BSP/kernel"
fi
[ "$(git -C "$BSP/kernel" rev-parse HEAD)" = "$ACK_SHA" ] || { echo "kernel/ is not at $ACK_SHA"; exit 1; }
[ "$(sed -n 1p "$DONORS/clo-kernel-6.12/android/ACK_SHA")" = "$ACK_SHA" ] || { echo "donor ACK_SHA changed"; exit 1; }
# Patches to ACK itself (patches/kernel/*.patch), applied once each.
for p in "$BSP"/patches/kernel/*.patch; do
  [ -e "$p" ] || continue
  if git -C "$BSP/kernel" apply --reverse --check "$p" 2>/dev/null; then continue; fi
  git -C "$BSP/kernel" apply "$p"; echo "applied to kernel: $(basename "$p")"
done

# 2. soc-repo: private copy of the donor + our patches (patches/soc-repo/*.patch).
#    KEEP_EDITS=1 skips the reset of soc-repo/ and devicetree/ (while working on a fix there,
#    before tools/mkpatch.sh has turned it into a patch file).
if [ -z "${KEEP_EDITS:-}" ]; then
  rsync -a --delete --exclude=.git/ --exclude=.gitignore "$DONORS/clo-kernel-6.12/" "$BSP/soc-repo/"
  for p in "$BSP"/patches/soc-repo/*.patch; do
    [ -e "$p" ] || continue
    patch -d "$BSP/soc-repo" -p1 --batch -s < "$p"; echo "applied to soc-repo: $(basename "$p")"
  done
fi
# Kconfig.ext: kleaf generates it by flattening Kconfig.msm; sourcing it is equivalent.
printf '# generated by assemble.sh\nsource "$(KCONFIG_EXT_PREFIX)Kconfig.msm"\n' > "$BSP/soc-repo/Kconfig.ext"

# 3. soc-repo-staging: same three steps as STAGE_COMMON_SOURCES in build/common_sources.mk.
#    Object files of the module build land here too, so keep them across runs (no --delete).
ST=$BSP/soc-repo-staging
mkdir -p "$ST"
rsync -a --prune-empty-dirs --include='/drivers/' --include='/drivers/**/' --include='/net/' \
  --include='/net/**/' --include='*.c' --include='*.h' --exclude='*' "$BSP/kernel/" "$ST/"
# The rsync filter above (Qualcomm's) only takes drivers/ and net/. soc-repo Makefiles also
# build ACK files from elsewhere (common_sources.bzl COPY_FILES: lib/crc-itu-t.c for the
# aquantia PHY, sound/virtio/*); kleaf copies those one by one. Stage them the same way.
sed -n 's/^ *"\(\(lib\|sound\)\/[^"]*\)",$/\1/p' "$BSP/soc-repo/common_sources.bzl" | while read -r f; do
  [ -f "$BSP/kernel/$f" ] && install -D -p -m644 "$BSP/kernel/$f" "$ST/$f"
done
rsync -a "$BSP/soc-repo/" "$ST/"
# dst|src|diff, copied from COMMON_PATCH_FILES in build/common_sources.mk
for rec in \
  'drivers/regulator/qti_fixed_regulator.c|drivers/regulator/fixed.c|drivers/regulator/fixed.diff' \
  'drivers/dma/qcom/gpi_fixed.c|drivers/dma/qcom/gpi.c|drivers/dma/qcom/gpi_fix.diff' \
  'drivers/net/virtio_net.c|drivers/net/virtio_net.c|drivers/net/virtio_net_fix.diff'; do
  dst=${rec%%|*}; tmp=${rec#*|}; src=${tmp%%|*}; diff=${tmp#*|}
  mkdir -p "$ST/$(dirname "$dst")"
  patch --follow-symlinks -p0 --batch -s -o "$ST/$dst.new" -i "$BSP/soc-repo/$diff" "$BSP/kernel/$src"
  cmp -s "$ST/$dst.new" "$ST/$dst" 2>/dev/null && rm "$ST/$dst.new" || mv "$ST/$dst.new" "$ST/$dst"
done

# 4. devicetree: private copy + our patches, linked where KP 5.0 has it.
if [ -z "${KEEP_EDITS:-}" ]; then
  rsync -a --delete --exclude=.git/ "$DONORS/clo-devicetree-6.12/" "$BSP/devicetree/"
  for p in "$BSP"/patches/devicetree/*.patch; do
    [ -e "$p" ] || continue
    patch -d "$BSP/devicetree" -p1 --batch -s < "$p"; echo "applied to devicetree: $(basename "$p")"
  done
fi
ln -sfn ../../../../../devicetree "$BSP/kernel/arch/arm64/boot/dts/vendor"

# 5. Config fragment: configs/lahaina_perf.bzl (a Starlark dict) -> Kconfig fragment,
#    the same mapping as kleaf-scripts/defconfig_fragment.bzl ("n" -> "is not set").
sed -n 's/^ *"\(CONFIG_[A-Za-z0-9_]*\)": "\(.*\)",$/\1=\2/p' "$BSP/soc-repo/configs/lahaina_perf.bzl" \
  | sed -e 's/\\"/"/g' -e 's/^\(CONFIG_[A-Za-z0-9_]*\)=n$/# \1 is not set/' > "$BSP/lahaina_perf.fragment"
n=$(grep -c 'CONFIG_' "$BSP/soc-repo/configs/lahaina_perf.bzl"); m=$(grep -c CONFIG_ "$BSP/lahaina_perf.fragment")
[ "$n" = "$m" ] || { echo "fragment conversion lost lines ($m of $n)"; exit 1; }
echo "assembled: kernel $(git -C "$BSP/kernel" rev-parse --short HEAD), soc-repo, staging, devicetree, fragment ($m symbols)"
