#!/usr/bin/env python3
"""Decode a downstream (qcom,mdss-dsi-*-command) DSI command blob into mainline
mipi_dsi_*_multi() calls, the way the generated parts of drivers/gpu/drm/panel/
panel-samsung-s6e3fc3.c were made.

Usage: dsi-cmd2c.py <downstream dts> <panel node label> <property> [timing node]
  e.g. dsi-cmd2c.py downstream-dt/a52sxq-r02.dts ss_dsi_panel_S6E3FC3_AMS646YD01_LO_FHD \
           qcom,mdss-dsi-on-command fhd60
Without a timing node the property is looked up directly in the panel node
(samsung,display_on_tx_cmds_revA etc.).

Blob format (dsi_panel.c, 5.4): per command a 7-byte header
  [data type, last, vc, ack, wait ms, len hi, len lo] then len payload bytes.
Data types: 0x05/0x15/0x39 DCS, 0x29 generic long (Samsung sends every write as 0x29;
mainline panel drivers use DCS writes for these DDICs, s6e3fc2x01/s6e3ha8 do the same),
0x07 compression mode, 0x0a picture parameter set.
The PPS payload is printed as a C array for comparison only: the driver packs its own
PPS from struct drm_dsc_config (drm_dsc_pps_payload_pack()).
"""
import re
import sys

KEYS = {
    (0x9f, 0xa5, 0xa5): "s6e3fc3_test_key_on_lvl1",
    (0x9f, 0x5a, 0x5a): "s6e3fc3_test_key_off_lvl1",
    (0xf0, 0x5a, 0x5a): "s6e3fc3_test_key_on_lvl2",
    (0xf0, 0xa5, 0xa5): "s6e3fc3_test_key_off_lvl2",
    (0xfc, 0x5a, 0x5a): "s6e3fc3_test_key_on_lvl3",
    (0xfc, 0xa5, 0xa5): "s6e3fc3_test_key_off_lvl3",
}


def find_blob(text, label, prop, timing):
    m = re.search(r"\b%s: %s \{" % (re.escape(label), re.escape(label)), text)
    if not m:
        sys.exit(f"panel node {label} not found")
    body = text[m.end():]
    if timing:
        t = re.search(r"\b%s \{" % re.escape(timing), body)
        if not t:
            sys.exit(f"timing node {timing} not found")
        body = body[t.end():]
    p = re.search(r"\b%s = \[([0-9a-fA-F ]*)\];" % re.escape(prop), body)
    if not p:
        sys.exit(f"{prop} not found (only [..] byte blobs are handled)")
    return [int(x, 16) for x in p.group(1).split()]


def decode(b):
    i, cmds = 0, []
    while i < len(b):
        if i + 7 > len(b):
            sys.exit(f"truncated header at {i}")
        dtype, wait, n = b[i], b[i + 4], (b[i + 5] << 8) | b[i + 6]
        payload = b[i + 7:i + 7 + n]
        if len(payload) != n:
            sys.exit(f"truncated payload at {i}")
        cmds.append((dtype, wait, payload))
        i += 7 + n
    return cmds


def hexl(p):
    return ", ".join(f"0x{x:02x}" for x in p)


def emit(cmds, ctx="&dsi_ctx"):
    out = []
    for dtype, wait, p in cmds:
        t = tuple(p)
        if dtype == 0x0a:
            out.append(f"\t/* PPS ({len(p)} bytes downstream): packed from ctx->dsc */")
            out.append(f"\tdrm_dsc_pps_payload_pack(&pps, &ctx->dsc);")
            out.append(f"\tmipi_dsi_picture_parameter_set_multi({ctx}, &pps);")
        elif dtype == 0x07:
            out.append(f"\tmipi_dsi_compression_mode_multi({ctx}, {'true' if p[0] else 'false'});")
        elif t in KEYS:
            out.append(f"\t{KEYS[t]}({ctx});")
        elif t == (0x11, 0x00) or t == (0x11,):
            out.append(f"\tmipi_dsi_dcs_exit_sleep_mode_multi({ctx});")
        elif t == (0x10, 0x00) or t == (0x10,):
            out.append(f"\tmipi_dsi_dcs_enter_sleep_mode_multi({ctx});")
        elif t == (0x29, 0x00) or t == (0x29,):
            out.append(f"\tmipi_dsi_dcs_set_display_on_multi({ctx});")
        elif t == (0x28, 0x00) or t == (0x28,):
            out.append(f"\tmipi_dsi_dcs_set_display_off_multi({ctx});")
        elif t == (0x35, 0x00):
            out.append(f"\tmipi_dsi_dcs_set_tear_on_multi({ctx}, MIPI_DSI_DCS_TEAR_MODE_VBLANK);")
        elif p[0] in (0x2a, 0x2b) and len(p) == 5:
            fn = "column" if p[0] == 0x2a else "page"
            out.append(f"\tmipi_dsi_dcs_set_{fn}_address_multi({ctx}, 0x{(p[1] << 8) | p[2]:04x}, "
                       f"0x{(p[3] << 8) | p[4]:04x});")
        else:
            line = f"\tmipi_dsi_dcs_write_seq_multi({ctx}, {hexl(p)});"
            if len(line.expandtabs()) > 100:
                # wrap like the upstream drivers: 8 bytes per continuation line
                parts = [hexl(p[:1])] + [hexl(p[k:k + 8]) for k in range(1, len(p), 8)]
                line = f"\tmipi_dsi_dcs_write_seq_multi({ctx}, " + \
                    ",\n\t\t\t\t     ".join(parts) + ");"
            out.append(line)
        if wait:
            out.append(f"\tmipi_dsi_msleep({ctx}, {wait});")
    return "\n".join(out)


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    text = open(sys.argv[1]).read()
    timing = sys.argv[4] if len(sys.argv) > 4 else None
    cmds = decode(find_blob(text, sys.argv[2], sys.argv[3], timing))
    print(f"\t/* generated by tools/dsi-cmd2c.py from {sys.argv[3]}"
          f"{' (' + timing + ')' if timing else ''} */")
    print(emit(cmds))
    for dtype, _, p in cmds:
        if dtype == 0x0a:
            print("\n/* downstream PPS, for comparison */")
            print("static const u8 s6e3fc3_downstream_pps[] = {")
            for k in range(0, len(p), 8):
                print("\t" + hexl(p[k:k + 8]) + ",")
            print("};")


if __name__ == "__main__":
    main()
